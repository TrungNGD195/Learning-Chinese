  await page.getByLabel('Hiện pinyin',{exact:true}).uncheck()
  await page.waitForFunction(({selector,count})=>document.querySelectorAll(selector).length===count,{selector:'.ap-dialogue .ap-pinyin',count:0})
  await shot(page,`reading-${width}`)
