  await page.locator('.ap-answer-options label').filter({hasText:'我是老师。'}).click();await page.getByRole('button',{name:'Kiểm tra đáp án'}).click();await page.getByRole('button',{name:'Câu tiếp theo'}).click()
  await page.locator('.ap-answer-options label').filter({hasText:'的'}).click();await page.getByRole('button',{name:'Kiểm tra đáp án'}).click();await page.getByRole('button',{name:'Câu tiếp theo'}).click()
